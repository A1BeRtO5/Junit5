package org.example;

public class Calculator {
    public int add(int a, int b) {
        return a+b;
    }
    public int minus(int a, int b) {
        return a-b;
    }
    public double divide(Integer a, Integer b) {
        return (double) a /b;
    }
    public double multiply(int a, int b) {
        return a*b*1.0;
    }
}

